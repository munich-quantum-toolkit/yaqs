"""Stage 2b (validation): fixed-rank gate-window locality of the TDVP vector field (spec 3.2).

For random normalized complex MPS, the instantaneous physical tangent vector
of the fixed-rank TDVP flow generated by a two-site gate generator G on sites
(q0, q1),

    phi = P_T ( -i G |psi> ),

is computed two ways and compared as dense physical vectors:

  1. full-chain fixed-rank tangent projector
         P_T = sum_k P_{<k} (x) I_k (x) P_{>k}  -  sum_c P_{<=c} (x) P_{>c},
     where P_{<=c} / P_{>c} project onto the retained left/right Schmidt
     subspaces at cut c (subspace ranks = the MPS bond dimensions);
  2. the same sum restricted to the gate-spanning window [q0, q1]
     (one-site terms k in [q0, q1], bond terms for cuts inside the window),
     with identical boundary support spaces.

Everything is built independently with dense linear algebra (no reuse of the
production TDVP code), so gauge conventions cannot masquerade as agreement.

Records r_loc = ||phi_full - phi_win|| / max(||phi_full||, 1e-30), the
absolute residual, Schmidt-spectrum conditioning at each cut, and the norm
derivative 2 Re<psi|phi_full>. Asserts r_loc < 1e-10.

Note: the corresponding full-chain-versus-one-site-halo check for the
adaptive two-site variation space is not run: the production code does not
expose the two-site variation-space action as a standalone object, and the
spec forbids building a second numerical framework for this optional
diagnostic.

Usage:
    uv run python paper_benchmarks/scripts/validate_locality.py
"""

from __future__ import annotations

import csv

import numpy as np
from pb_common import (
    LOGS_DIR,
    PROCESSED_DIR,
    TABLES_DIR,
    limit_blas_threads,
    save_json,
)

limit_blas_threads()

L = 10
CHI = 4
R_LOC_TOL = 1e-10
SEEDS = (101, 102, 103, 104, 105)
CASES = {"nearest_neighbour": (4, 5), "long_range": (2, 7)}
PAULI = {
    "x": np.array([[0, 1], [1, 0]], dtype=np.complex128),
    "y": np.array([[0, -1j], [1j, 0]], dtype=np.complex128),
    "z": np.array([[1, 0], [0, -1]], dtype=np.complex128),
}


def bond_profile(length: int, chi: int) -> list[int]:
    return [min(2**i, 2 ** (length - i), chi) for i in range(length + 1)]


def random_dense_mps_state(length: int, chi: int, rng: np.random.Generator) -> np.ndarray:
    """Normalized dense state of exact bond profile min(2^i, 2^(L-i), chi).

    Contraction order gives psi[s_0, s_1, ..., s_{L-1}] flattened row-major
    (site 0 slowest); the convention is used consistently everywhere here.
    """
    prof = bond_profile(length, chi)
    tensors = []
    for site in range(length):
        shape = (prof[site], 2, prof[site + 1])
        tensors.append(
            rng.standard_normal(shape) + 1j * rng.standard_normal(shape)
        )
    psi = tensors[0]
    for t in tensors[1:]:
        psi = np.tensordot(psi, t, axes=([-1], [0]))
    psi = psi.reshape(-1)
    return psi / np.linalg.norm(psi)


def schmidt_subspaces(psi: np.ndarray, length: int, chi: int):
    """Retained left/right singular subspaces and spectra at every cut."""
    prof = bond_profile(length, chi)
    lefts, rights, spectra = {}, {}, {}
    for cut in range(1, length):
        m = psi.reshape(2**cut, 2 ** (length - cut))
        u, s, vh = np.linalg.svd(m, full_matrices=False)
        r = prof[cut]
        lefts[cut] = u[:, :r]
        rights[cut] = vh[:r, :].conj().T
        spectra[cut] = s
    return lefts, rights, spectra, prof


def apply_generator(psi: np.ndarray, gate_axis: str, theta: float, q0: int, q1: int, length: int) -> np.ndarray:
    """W = -i G psi with G = (theta/2) P_{q0} P_{q1} (product generator, D_g = 1)."""
    p = PAULI[gate_axis]
    t = psi.reshape([2] * length)
    t = np.tensordot(p, t, axes=([1], [q0]))
    t = np.moveaxis(t, 0, q0)
    t = np.tensordot(p, t, axes=([1], [q1]))
    t = np.moveaxis(t, 0, q1)
    return (-1j * theta / 2.0) * t.reshape(-1)


def one_site_term(w: np.ndarray, k: int, lefts, rights, length: int) -> np.ndarray:
    t = w.reshape(2**k, 2 * 2 ** (length - k - 1))
    if k > 0:
        u = lefts[k]
        t = u @ (u.conj().T @ t)
    t = t.reshape(2**k * 2, 2 ** (length - k - 1))
    if k < length - 1:
        v = rights[k + 1]
        t = (t @ v) @ v.conj().T
    return t.reshape(-1)


def bond_term(w: np.ndarray, cut: int, lefts, rights, length: int) -> np.ndarray:
    m = w.reshape(2**cut, 2 ** (length - cut))
    u = lefts[cut]
    v = rights[cut]
    m = u @ (u.conj().T @ m)
    m = (m @ v) @ v.conj().T
    return m.reshape(-1)


def tangent_projection(w: np.ndarray, lefts, rights, length: int, sites, cuts) -> np.ndarray:
    phi = np.zeros_like(w)
    for k in sites:
        phi += one_site_term(w, k, lefts, rights, length)
    for c in cuts:
        phi -= bond_term(w, c, lefts, rights, length)
    return phi


def main() -> int:
    rows = []
    failed = False
    theta = 2.0 * np.pi * 0.1  # fixed nontrivial generator strength
    for case, (q0, q1) in CASES.items():
        for axis in ("x", "y", "z"):
            for seed in SEEDS:
                rng = np.random.default_rng(seed)
                psi = random_dense_mps_state(L, CHI, rng)
                lefts, rights, spectra, prof = schmidt_subspaces(psi, L, CHI)
                w = apply_generator(psi, axis, theta, q0, q1, L)

                phi_full = tangent_projection(
                    w, lefts, rights, L, sites=range(L), cuts=range(1, L),
                )
                phi_win = tangent_projection(
                    w, lefts, rights, L,
                    sites=range(q0, q1 + 1), cuts=range(q0 + 1, q1 + 1),
                )
                abs_res = float(np.linalg.norm(phi_full - phi_win))
                denom = max(float(np.linalg.norm(phi_full)), 1e-30)
                r_loc = abs_res / denom
                # conditioning of the retained Schmidt subspaces
                sigma_min_ret = min(
                    float(spectra[c][prof[c] - 1]) for c in range(1, L)
                )
                sigma_max_disc = max(
                    float(spectra[c][prof[c]]) if len(spectra[c]) > prof[c] else 0.0
                    for c in range(1, L)
                )
                norm_derivative = float(2.0 * np.real(np.vdot(psi, phi_full)))
                ok = r_loc < R_LOC_TOL
                failed = failed or not ok
                rows.append({
                    "case": case,
                    "generator": f"{axis}{axis}",
                    "q0": q0,
                    "q1": q1,
                    "separation": q1 - q0,
                    "seed": seed,
                    "L": L,
                    "chi": CHI,
                    "theta": theta,
                    "r_loc": r_loc,
                    "abs_residual": abs_res,
                    "phi_norm": denom,
                    "sigma_min_retained": sigma_min_ret,
                    "sigma_max_discarded": sigma_max_disc,
                    "norm_derivative": norm_derivative,
                    "pass": ok,
                })
                print(f"  {case:18s} {axis}{axis} seed={seed}: r_loc={r_loc:.3e} "
                      f"|phi|={denom:.3e} dnorm={norm_derivative:+.1e} "
                      f"{'PASS' if ok else 'FAIL'}")

    PROCESSED_DIR.mkdir(parents=True, exist_ok=True)
    out_csv = PROCESSED_DIR / "locality_residuals.csv"
    with out_csv.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        writer.writeheader()
        writer.writerows(rows)

    r = np.array([row["r_loc"] for row in rows])
    summary = {
        "description": "fixed-rank gate-window locality validation (spec 3.2)",
        "L": L,
        "chi": CHI,
        "theta": theta,
        "cases": {k: list(v) for k, v in CASES.items()},
        "seeds": list(SEEDS),
        "n_rows": len(rows),
        "r_loc_max": float(r.max()),
        "r_loc_median": float(np.median(r)),
        "abs_residual_max": float(max(row["abs_residual"] for row in rows)),
        "norm_derivative_max_abs": float(max(abs(row["norm_derivative"]) for row in rows)),
        "tolerance": R_LOC_TOL,
        "all_pass": not failed,
        "two_site_halo_check": (
            "skipped: two-site variation-space action not exposed by production "
            "code; spec forbids a second framework for this optional diagnostic"
        ),
    }
    save_json(LOGS_DIR / "validation_locality.json", summary)

    # compact LaTeX validation table (max / median per case-generator group)
    TABLES_DIR.mkdir(parents=True, exist_ok=True)
    lines = [
        r"% Auto-generated by paper_benchmarks/scripts/validate_locality.py",
        r"\begin{tabular}{llcc}",
        r"\hline\hline",
        r"case & generator & $\max r_{\mathrm{loc}}$ & median $r_{\mathrm{loc}}$ \\",
        r"\hline",
    ]
    for case in CASES:
        for axis in ("x", "y", "z"):
            grp = [row["r_loc"] for row in rows if row["case"] == case and row["generator"] == f"{axis}{axis}"]
            label = case.replace("_", " ")
            gen = f"${axis.upper()}\\otimes {axis.upper()}$"
            lines.append(
                f"{label} & {gen} & "
                f"$\\num{{{max(grp):.2e}}}$ & $\\num{{{float(np.median(grp)):.2e}}}$ \\\\"
            )
    lines += [r"\hline\hline", r"\end{tabular}", ""]
    (TABLES_DIR / "table_locality.tex").write_text("\n".join(lines), encoding="utf-8")

    print(f"\nmax r_loc = {summary['r_loc_max']:.3e}, median = {summary['r_loc_median']:.3e} "
          f"({'ALL PASS' if not failed else 'FAILURES PRESENT'})")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
